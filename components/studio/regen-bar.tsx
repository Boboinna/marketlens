"use client";
import { NOTES_MAX, RATIO_IDS, RATIOS, type StyleId, type VisualSettings } from "@/config/image-styles";
import { Button } from "../ui/button";
import { BackgroundPicker } from "./background-picker";
import { StylePicker } from "./style-picker";

interface Props {
  value: VisualSettings; onChange: (p: Partial<VisualSettings>) => void;
  hasSize: boolean; hasDetails: boolean; hasTitle: boolean;
  left: number; total: number; busy: boolean; canMake: boolean; onMake: () => void;
}

const select = "mt-1 h-12 w-full rounded-xl border border-line bg-s2 px-3 text-base text-tx outline-none disabled:opacity-60 sm:text-sm";

/**
 * Pick a different style, background or aspect ratio, add extra details in your own words, then make another visual.
 * Every visual is generated by the AI as an Amazon listing image. Shows how many attempts are left.
 */
export function RegenBar({ value, onChange, hasSize, hasDetails, hasTitle, left, total, busy, canMake, onMake }: Props) {
  const blocked = (id: StyleId) => (id === "size" && !hasSize ? "measurements with cm or in" : id === "infographic" && !hasDetails ? "a confirmed detail" : id === "social" && !hasTitle ? "what the product is" : null);
  return (
    <div className="mt-5 border-t border-line pt-4">
      <div className="grid gap-3 sm:grid-cols-2">
        <div><p className="mb-1 text-xs text-mu">Style</p><StylePicker compact value={value.style} onChange={(style) => onChange({ style })} blocked={blocked} /></div>
        <div><p className="mb-1 text-xs text-mu">Background</p><BackgroundPicker value={value.bg} onChange={(bg) => onChange({ bg })} /></div>
        <label className="text-xs text-mu">Aspect ratio
          <select className={select} disabled={busy} value={value.ratio} onChange={(e) => onChange({ ratio: e.target.value as VisualSettings["ratio"] })}>
            {RATIO_IDS.map((r) => <option key={r} value={r}>{r} · {RATIOS[r].label}</option>)}
          </select>
        </label>
      </div>

      <label className="mt-3 block text-xs text-mu">Extra details for this visual (optional)
        <textarea
          rows={3} disabled={busy} value={value.notes} maxLength={NOTES_MAX} onChange={(e) => onChange({ notes: e.target.value })}
          placeholder="Tell the AI what to change, e.g. show the product larger, warmer light, add a small plant on the left, lighter background"
          className="mt-1 w-full resize-y rounded-xl border border-line bg-s2 px-3.5 py-3 text-base text-tx outline-none disabled:opacity-60 sm:text-[15px]"
        />
        <span className="mt-1 flex justify-between gap-3">
          <span>Added after the fixed Amazon-listing instructions. Your product itself is never redesigned.</span>
          <span className="font-mono">{value.notes.length}/{NOTES_MAX}</span>
        </span>
      </label>

      <div className="mt-4 flex flex-col items-stretch gap-2 sm:flex-row sm:items-center">
        <Button disabled={!canMake} onClick={onMake} className="sm:w-auto">{busy ? "Making…" : left > 0 ? `Make another visual (${left} left)` : `All ${total} visuals used`}</Button>
        <p className="text-xs text-mu">{left > 0 ? "Deleting a visual doesn’t give the attempt back." : "Download the ones you like."}</p>
      </div>
    </div>
  );
}
